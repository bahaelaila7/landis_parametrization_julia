"""Write a run config = a base yaml + overrides (docs/nested_cv_gafl.md). Pan's strict loader validates the result (unknown keys are an error).
  python -I tools/ncv/mkcfg.py <base.yml> <out.yml> key=value [a.b=value ...]
Values are parsed as YAML (numbers, true/false, [lists], "" for empty strings); a dotted key sets a nested key; key=null deletes the key."""
import os, sys, yaml
base, out, *kv = sys.argv[1:]
cfg = yaml.safe_load(open(base))
for item in kv:
    k, v = item.split('=', 1)
    val = yaml.safe_load(v) if v != '' else ''
    d = cfg; parts = k.split('.')
    for p in parts[:-1]: d = d.setdefault(p, {})
    if val is None: d.pop(parts[-1], None)
    else: d[parts[-1]] = val
os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
with open(out, "w") as f:
    f.write(f'# generated by tools/ncv/mkcfg.py from {base}\n# overrides: {" ".join(kv)}\n')
    yaml.safe_dump(cfg, f, sort_keys=False, default_flow_style=None, width=200)
